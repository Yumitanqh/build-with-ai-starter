// Helper to generate realistic 24h occupancy curves based on carpark type and area
function generate24hHistory(peakHour: number, baseOccupancy: number, totalLots: number) {
  const hours = [
    '00:00', '02:00', '04:00', '06:00', '08:00', '10:00',
    '12:00', '14:00', '16:00', '18:00', '20:00', '22:00'
  ];
  return hours.map((hourStr, i) => {
    const hr = i * 2;
    // calculate bell curve distance to peak
    const dist = Math.abs(hr - peakHour);
    const variation = Math.max(0, 1 - dist / 8);
    const occupiedPercent = Math.min(98, Math.max(12, Math.round(baseOccupancy + variation * 35)));
    const occupiedLots = Math.round((occupiedPercent / 100) * totalLots);
    const availableLots = Math.max(0, totalLots - occupiedLots);
    return {
      hour: hourStr,
      occupiedPercent,
      availableLots,
    };
  });
}

